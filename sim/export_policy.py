"""
Export a trained PPO policy to src/flight/policy_weights.py for the board.

    cd sim
    uv run python export_policy.py runs/ppo_<time>/best.zip

Then
    uv run python watch.py --ctrl policy --random

shows the exported file flying, run through the board's own flight/policy.py.

Three steps:
1. Pull the actor network out of the SB3 zip: hidden layers (tanh) from
   mlp_extractor.policy_net, the output layer from action_net. The value
   network and the exploration noise stay behind - the board only needs the
   deterministic action.
2. Check the pure-Python copy against torch on observations from real
   episodes: the two must agree to ~1e-5 (the file stores 7 significant
   digits), or the export is wrong.
3. Fly it against lift.py's PID on the same 60 randomized drones (same seeds,
   same kicks, floor and mid-air starts) and print both.
"""

import argparse
import time
from pathlib import Path

import numpy as np
import torch
from stable_baselines3 import PPO

from pico_drone_sim.controllers import PIDController, PolicyController, rollout
from pico_drone_sim.env import HoverEnv

# isort: split
# (pico_drone_sim above puts ../src on sys.path, so `flight` imports after it)
from flight.policy import ACT_SCALE, Policy

OUT = Path(__file__).resolve().parent.parent / "src" / "flight" / "policy_weights.py"


def extract(model):
    """[(weights rows, biases), ...] in flight/policy.py's layout."""
    layers = []
    for module in model.policy.mlp_extractor.policy_net:
        if isinstance(module, torch.nn.Linear):
            layers.append(module)
        elif not isinstance(module, torch.nn.Tanh):
            raise SystemExit("unexpected layer %r: the board's runner only knows Linear + Tanh" % module)
    layers.append(model.policy.action_net)
    return [(lin.weight.detach().numpy().astype(float).tolist(),
             lin.bias.detach().numpy().astype(float).tolist()) for lin in layers]


def write(layers, source, note):
    def fmt(v):
        return "%.7g" % v

    lines = [
        '"""',
        "Trained levelling policy - GENERATED by sim/export_policy.py, do not edit.",
        "",
        "source: %s" % source,
        "exported: %s" % time.strftime("%Y-%m-%d %H:%M"),
        "network: %s, tanh hidden layers, linear output" % " -> ".join(
            [str(len(layers[0][0][0]))] + [str(len(b)) for _, b in layers]),
        note,
        '"""',
        "",
        "# LAYERS[k] = (weights, biases); weights[j] is output j's row of input weights.",
        "LAYERS = [",
    ]
    for w, b in layers:
        lines.append("    (")
        lines.append("        [")
        for row in w:
            lines.append("            [" + ", ".join(fmt(v) for v in row) + "],")
        lines.append("        ],")
        lines.append("        [" + ", ".join(fmt(v) for v in b) + "],")
        lines.append("    ),")
    lines.append("]")
    OUT.write_text("\n".join(lines) + "\n")


def check_match(model, policy, n=2000):
    """Largest difference between torch and the pure-Python copy on real observations."""
    env = HoverEnv(randomize_scale=1.0, seed=7)
    obs, _ = env.reset()
    worst = 0.0
    for _ in range(n):
        a_torch, _ = model.predict(obs, deterministic=True)
        a_torch = np.clip(a_torch, -1.0, 1.0) * ACT_SCALE
        a_py = np.array(policy.act([float(x) for x in obs]))
        worst = max(worst, float(np.max(np.abs(a_torch - a_py))))
        obs, _, term, trunc, _ = env.step(a_py / ACT_SCALE)
        if term or trunc:
            obs, _ = env.reset()
    return worst


def compare(layers, n=60):
    """Policy vs lift.py's PID on the same drones. Returns a one-line summary."""
    env = HoverEnv(randomize_scale=1.0)
    rows = {}
    for name, make in (("lift.py PID", PIDController), ("PPO policy", lambda: PolicyController(layers))):
        crashes, returns, rms = 0, [], []
        for s in range(n):
            log = rollout(env, make(), seed=5000 + s)
            crashes += log["crashed"]
            returns.append(log["return"])
            r, q = np.array(log["roll"]), np.array(log["pitch"])
            rms.append(float(np.sqrt(np.mean(r * r + q * q))))
        rows[name] = (crashes, float(np.mean(returns)), float(np.median(rms)))
        print("  %-12s crashed %2d/%d   mean return %5.0f   median RMS tilt %4.1f deg"
              % (name, crashes, n, rows[name][1], rows[name][2]))
    pid, pol = rows["lift.py PID"], rows["PPO policy"]
    return ("sim check (60 randomized drones, kicks): PPO crashed %d/%d, RMS tilt %.1f deg; "
            "lift.py PID crashed %d/%d, %.1f deg" % (pol[0], n, pol[2], pid[0], n, pid[2]))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("zip", type=Path, help="runs/ppo_<time>/best.zip")
    args = ap.parse_args()

    model = PPO.load(args.zip, device="cpu")
    layers = extract(model)
    policy = Policy(layers)
    print("network %s, %d multiply-adds per call"
          % (" -> ".join([str(policy.in_size)] + [str(len(b)) for _, b in layers]), policy.macs))

    worst = check_match(model, policy)
    print("pure Python vs torch: largest difference %.2e (in mixer units)" % worst)
    if worst > 1e-4:
        raise SystemExit("export does not match torch - not writing %s" % OUT)

    print("flying it against lift.py's PID on 60 randomized drones...")
    note = compare(layers)
    try:
        source = args.zip.resolve().relative_to(Path(__file__).resolve().parent)
    except ValueError:
        source = args.zip
    write(layers, "sim/%s" % source, note)
    print("wrote", OUT)
    print("watch it: uv run python watch.py --ctrl policy --random")


if __name__ == "__main__":
    main()
